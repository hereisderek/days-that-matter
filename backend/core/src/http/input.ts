// Small checks of request bodies and parameters that are not event or memo documents.
import type { Json, JsonObject } from '../rules/merge.ts';
import { invalidPayload } from './errors.ts';
import type { Validated } from '../rules/validation.ts';

/** Fails with `400 invalid_payload` when the body has a key outside `allowed`. */
export function onlyFields(body: JsonObject, allowed: readonly string[]): void {
  if (!Object.keys(body).every((k) => allowed.includes(k))) throw invalidPayload('', 'unknown field');
}

/** A required string member of at most `max` characters (UTF-16 units). */
export function requiredString(body: JsonObject, key: string, max: number): string {
  const value: Json | undefined = body[key];
  if (value === undefined || value === null) throw invalidPayload(key, 'required');
  if (typeof value !== 'string') throw invalidPayload(key, 'must be a string');
  if (value.length === 0 || value.length > max) throw invalidPayload(key, `must be 1 to ${max} characters`);
  return value;
}

/** The value of a validation, or `400 invalid_payload` naming the first failing field. */
export function valid<T>(result: Validated<T>): T {
  if (result.valid) return result.value;
  const first = result.errors[0] as { field: string; reason: string };
  throw invalidPayload(first.field, first.reason);
}

const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/;

/** Event and memo ids are lower-case UUIDs generated by the client. */
export function isUuid(text: string): boolean {
  return UUID.test(text);
}
